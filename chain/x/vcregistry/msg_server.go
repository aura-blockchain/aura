// RegisterDID handles DID registration
func (s *msgServer) RegisterDID(ctx context.Context, msg *vcregistrypb.MsgRegisterDID) (*vcregistrypb.MsgRegisterDIDResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate inputs
	if msg.Controller == "" {
		return nil, types.ErrInvalidController
	}
	if msg.Did == "" {
		return nil, types.ErrInvalidDID
	}

	// Check if DID already exists
	if _, ok := s.keeper.GetDIDDocument(msg.Did); ok {
		return nil, types.ErrDIDAlreadyExists
	}

	// Register DID
	if err := s.keeper.RegisterDID(msg.Did, msg.Controller, msg.VerificationMethods, msg.MetadataUri); err != nil {
		return nil, err
	}

	createdAt := timestamppb.Now()

	return &vcregistrypb.MsgRegisterDIDResponse{
		Did:       msg.Did,
		CreatedAt: createdAt,
	}, nil
}

// UpdateDIDDocument handles DID document updates
func (s *msgServer) UpdateDIDDocument(ctx context.Context, msg *vcregistrypb.MsgUpdateDIDDocument) (*vcregistrypb.MsgUpdateDIDDocumentResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate inputs
	if msg.Controller == "" {
		return nil, types.ErrInvalidController
	}
	if msg.Did == "" {
		return nil, types.ErrInvalidDID
	}

	// Get existing DID document
	existingDoc, ok := s.keeper.GetDIDDocument(msg.Did)
	if !ok {
		return nil, types.ErrDIDNotFound
	}

	// Verify controller matches
	if existingDoc.Controller != msg.Controller {
		return nil, types.ErrUnauthorized
	}

	// Update DID document
	if err := s.keeper.UpdateDIDDocument(msg.Did, msg.VerificationMethods, msg.MetadataUri); err != nil {
		return nil, err
	}

	updatedAt := timestamppb.Now()

	return &vcregistrypb.MsgUpdateDIDDocumentResponse{
		UpdatedAt: updatedAt,
	}, nil
}

// incrementVersion increments a semantic version string
// Simple implementation: increments the minor version
func incrementVersion(version string) string {
	// Simple implementation - in production, use proper semver library
	if version == "" {
		return "1.0.0"
	}
	// For simplicity, just append .1 or increment
	return version + ".1"
}
