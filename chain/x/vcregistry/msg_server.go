type msgServer struct {
	vcregistrypb.UnimplementedMsgServer
	keeper *keeper.Keeper
}

// NewMsgServer creates a new message server
func NewMsgServer(keeper *keeper.Keeper) vcregistrypb.MsgServer {
	return &msgServer{keeper: keeper}
}

// MintVC handles VC minting
func (s *msgServer) MintVC(ctx context.Context, msg *vcregistrypb.MsgMintVC) (*vcregistrypb.MsgMintVCResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate inputs
	if msg.HolderAddress == "" {
		return nil, types.ErrInvalidHolderAddress
	}
	if msg.HolderDid == "" {
		return nil, types.ErrInvalidDID
	}
	if msg.VcType == types.VCTypeUnspecified {
		return nil, types.ErrInvalidVCType
	}

	// Check rate limiting
	if err := s.keeper.CheckMintRateLimit(msg.HolderAddress); err != nil {
		return nil, err
	}

	// Check if DID exists
	if _, ok := s.keeper.GetDIDDocument(msg.HolderDid); !ok {
		return nil, types.ErrDIDNotFound
	}

	// Get policy for this VC type
	vcTypeName := msg.VcType.String()
	if msg.VcType == types.VCTypeCustom {
		vcTypeName = msg.VcTypeCustom
	}

	policy, ok := s.keeper.GetVCPolicy(vcTypeName)
	if !ok {
		return nil, types.ErrPolicyNotFound
	}

	// Check policy status
	if policy.Status != types.VCPolicyStatusActive {
		if policy.Status == types.VCPolicyStatusDeprecated {
			return nil, types.ErrPolicyDeprecated
		}
		return nil, types.ErrPolicyInactive
	}

	// Check singleton constraint
	if policy.Singleton {
		existingVCs := s.keeper.ListUserVCs(msg.HolderAddress, types.VCStatusActive, msg.VcType)
		if len(existingVCs) > 0 {
			return nil, types.ErrSingletonViolation
		}
	}

	// Generate VC ID
	vcID := s.keeper.GenerateVCID(msg.HolderAddress, msg.VcType)

	// Calculate expiry
	now := time.Now()
	var expiresAt *timestamppb.Timestamp
	if policy.ExpiryDurationDays > 0 {
		expiryTime := now.AddDate(0, 0, int(policy.ExpiryDurationDays))
		expiresAt = timestamppb.New(expiryTime)
	}

	// Create VC record
	issuedAt := timestamppb.New(now)
	vcRecord := types.VCRecord{
		VcId:               vcID,
		VcType:             msg.VcType,
		VcTypeCustom:       msg.VcTypeCustom,
		HolderDid:          msg.HolderDid,
		HolderAddress:      msg.HolderAddress,
		Status:             types.VCStatusActive,
		IssuedAt:           issuedAt,
		ExpiresAt:          expiresAt,
		IssuedHeight:       0,        // Set by keeper
		CredentialHash:     []byte{}, // Generated by keeper
		VerifierPluginHash: []byte{},
		IssuerAssistant:    "",
		PrerequisiteIrIds:  policy.RequiredIrIds,
		Metadata:           msg.Metadata,
		CsAtMint:           0, // Set by keeper
		PolicyVersion:      policy.Version,
	}

	// Store VC record
	if err := s.keeper.SetVCRecord(vcRecord); err != nil {
		return nil, err
	}

	// Add VC to DID document
	if err := s.keeper.AddCredentialToDID(msg.HolderDid, vcID); err != nil {
		return nil, err
	}

	// Increment mint count for rate limiting
	s.keeper.IncrementMintCount(msg.HolderAddress)

	// Emit event
	// Note: Events would be emitted via SDK context in actual implementation

	return &vcregistrypb.MsgMintVCResponse{
		VcId:           vcID,
		IssuedAt:       issuedAt,
		ExpiresAt:      expiresAt,
		CredentialHash: vcRecord.CredentialHash,
	}, nil
}

// RevokeVC handles user-initiated VC revocation
func (s *msgServer) RevokeVC(ctx context.Context, msg *vcregistrypb.MsgRevokeVC) (*vcregistrypb.MsgRevokeVCResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate inputs
	if msg.HolderAddress == "" {
		return nil, types.ErrInvalidHolderAddress
	}
	if msg.VcId == "" {
		return nil, types.ErrInvalidVCID
	}

	// Get VC record
	vcRecord, ok := s.keeper.GetVCRecord(msg.VcId)
	if !ok {
		return nil, types.ErrVCNotFound
	}

	// Verify signer is the holder
	if vcRecord.HolderAddress != msg.HolderAddress {
		return nil, types.ErrNotVCHolder
	}

	// Revoke the VC
	if err := s.keeper.RevokeVC(msg.VcId, types.RevocationReasonUserRequest, msg.HolderAddress, msg.ReasonText); err != nil {
		return nil, err
	}

	// Remove from DID document
	if err := s.keeper.RemoveCredentialFromDID(vcRecord.HolderDid, msg.VcId); err != nil {
		return nil, err
	}

	revokedAt := timestamppb.Now()

	return &vcregistrypb.MsgRevokeVCResponse{
		RevokedAt:     revokedAt,
		MerkleUpdated: true,
	}, nil
}

// AdminRevokeVC handles governance-initiated VC revocation
func (s *msgServer) AdminRevokeVC(ctx context.Context, msg *vcregistrypb.MsgAdminRevokeVC) (*vcregistrypb.MsgAdminRevokeVCResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate authority (governance module address)
	if msg.Authority == "" {
		return nil, types.ErrNotGovernance
	}

	// Verify authority is governance
	if msg.Authority != s.keeper.GetAuthority() {
		return nil, fmt.Errorf("invalid authority; expected %s, got %s", s.keeper.GetAuthority(), msg.Authority)
	}

	// Validate inputs
	if msg.VcId == "" {
		return nil, types.ErrInvalidVCID
	}

	// Get VC record
	vcRecord, ok := s.keeper.GetVCRecord(msg.VcId)
	if !ok {
		return nil, types.ErrVCNotFound
	}

	// Revoke the VC
	if err := s.keeper.RevokeVC(msg.VcId, msg.Reason, "governance", msg.Evidence); err != nil {
		return nil, err
	}

	// Remove from DID document
	if err := s.keeper.RemoveCredentialFromDID(vcRecord.HolderDid, msg.VcId); err != nil {
		return nil, err
	}

	revokedAt := timestamppb.Now()

	return &vcregistrypb.MsgAdminRevokeVCResponse{
		RevokedAt:     revokedAt,
		MerkleUpdated: true,
	}, nil
}

// SuspendVC handles VC suspension
func (s *msgServer) SuspendVC(ctx context.Context, msg *vcregistrypb.MsgSuspendVC) (*vcregistrypb.MsgSuspendVCResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate authority (governance module address)
	if msg.Authority == "" {
		return nil, types.ErrNotGovernance
	}

	// Validate inputs
	if msg.VcId == "" {
		return nil, types.ErrInvalidVCID
	}

	// Get VC record
	vcRecord, ok := s.keeper.GetVCRecord(msg.VcId)
	if !ok {
		return nil, types.ErrVCNotFound
	}

	// Check if already revoked or expired
	if vcRecord.Status == types.VCStatusRevoked {
		return nil, types.ErrVCAlreadyRevoked
	}
	if vcRecord.Status == types.VCStatusExpired {
		return nil, types.ErrVCExpired
	}

	// Update status to suspended
	vcRecord.Status = types.VCStatusSuspended
	if err := s.keeper.SetVCRecord(vcRecord); err != nil {
		return nil, err
	}

	suspendedAt := timestamppb.Now()
	var reactivateAt *timestamppb.Timestamp
	if msg.SuspensionDurationDays > 0 {
		reactivateTime := time.Now().AddDate(0, 0, int(msg.SuspensionDurationDays))
		reactivateAt = timestamppb.New(reactivateTime)
	}

	return &vcregistrypb.MsgSuspendVCResponse{
		SuspendedAt:  suspendedAt,
		ReactivateAt: reactivateAt,
	}, nil
}

// ReactivateVC handles VC reactivation
func (s *msgServer) ReactivateVC(ctx context.Context, msg *vcregistrypb.MsgReactivateVC) (*vcregistrypb.MsgReactivateVCResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate authority (governance module address)
	if msg.Authority == "" {
		return nil, types.ErrNotGovernance
	}

	// Validate inputs
	if msg.VcId == "" {
		return nil, types.ErrInvalidVCID
	}

	// Get VC record
	vcRecord, ok := s.keeper.GetVCRecord(msg.VcId)
	if !ok {
		return nil, types.ErrVCNotFound
	}

	// Check if suspended
	if vcRecord.Status != types.VCStatusSuspended {
		return nil, fmt.Errorf("VC is not suspended")
	}

	// Check if expired
	if vcRecord.ExpiresAt != nil && vcRecord.ExpiresAt.AsTime().Before(time.Now()) {
		vcRecord.Status = types.VCStatusExpired
		s.keeper.SetVCRecord(vcRecord)
		return nil, types.ErrVCExpired
	}

	// Update status to active
	vcRecord.Status = types.VCStatusActive
	if err := s.keeper.SetVCRecord(vcRecord); err != nil {
		return nil, err
	}

	reactivatedAt := timestamppb.Now()

	return &vcregistrypb.MsgReactivateVCResponse{
		ReactivatedAt: reactivatedAt,
	}, nil
}

// CreateVCPolicy handles VC policy creation
func (s *msgServer) CreateVCPolicy(ctx context.Context, msg *vcregistrypb.MsgCreateVCPolicy) (*vcregistrypb.MsgCreateVCPolicyResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate authority (governance module address)
	if msg.Authority == "" {
		return nil, types.ErrNotGovernance
	}

	// Validate inputs
	if msg.VcTypeName == "" {
		return nil, types.ErrInvalidVCType
	}

	// Check if policy already exists
	if _, ok := s.keeper.GetVCPolicy(msg.VcTypeName); ok {
		return nil, fmt.Errorf("policy already exists for type: %s", msg.VcTypeName)
	}

	// Create policy
	now := timestamppb.Now()
	policy := types.VCPolicy{
		VcTypeName:            msg.VcTypeName,
		VcTypeEnum:            msg.VcTypeEnum,
		CsThreshold:           msg.CsThreshold,
		RequiredIrIds:         msg.RequiredIrIds,
		RequiredArena:         msg.RequiredArena,
		RequiredArenaScore:    msg.RequiredArenaScore,
		ExpiryDurationDays:    msg.ExpiryDurationDays,
		Singleton:             msg.Singleton,
		RequiresAnnualRenewal: msg.RequiresAnnualRenewal,
		MetadataUri:           msg.MetadataUri,
		Status:                types.VCPolicyStatusActive,
		Version:               "1.0.0",
		CreatedAt:             now,
		CreatedHeight:         0, // Set by keeper
		Creator:               msg.Authority,
	}

	// Store policy
	if err := s.keeper.SetVCPolicy(policy); err != nil {
		return nil, err
	}

	return &vcregistrypb.MsgCreateVCPolicyResponse{
		PolicyId: msg.VcTypeName,
		Version:  policy.Version,
	}, nil
}

// UpdateVCPolicy handles VC policy updates
func (s *msgServer) UpdateVCPolicy(ctx context.Context, msg *vcregistrypb.MsgUpdateVCPolicy) (*vcregistrypb.MsgUpdateVCPolicyResponse, error) {
	if msg == nil {
		return nil, fmt.Errorf("msg required")
	}

	// Validate authority (governance module address)
	if msg.Authority == "" {
		return nil, types.ErrNotGovernance
	}

	// Validate inputs
	if msg.VcTypeName == "" {
		return nil, types.ErrInvalidVCType
	}

	// Get existing policy
	existingPolicy, ok := s.keeper.GetVCPolicy(msg.VcTypeName)
	if !ok {
		return nil, types.ErrPolicyNotFound
	}

	// Check if deprecated
	if existingPolicy.Status == types.VCPolicyStatusDeprecated {
		return nil, types.ErrPolicyDeprecated
	}

	// Increment version
	newVersion := incrementVersion(existingPolicy.Version)

	// Update policy with new values
	existingPolicy.CsThreshold = msg.CsThreshold
	existingPolicy.RequiredIrIds = msg.RequiredIrIds
	existingPolicy.RequiredArena = msg.RequiredArena
	existingPolicy.RequiredArenaScore = msg.RequiredArenaScore
	existingPolicy.ExpiryDurationDays = msg.ExpiryDurationDays
	existingPolicy.Singleton = msg.Singleton
	existingPolicy.RequiresAnnualRenewal = msg.RequiresAnnualRenewal
	existingPolicy.MetadataUri = msg.MetadataUri
	existingPolicy.Version = newVersion

	// Store updated policy
	if err := s.keeper.SetVCPolicy(existingPolicy); err != nil {
		return nil, err
	}

	return &vcregistrypb.MsgUpdateVCPolicyResponse{
		NewVersion: newVersion,
	}, nil
}

